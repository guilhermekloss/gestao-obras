const linha = (texto: string) => construirDoc(montarTexto(texto)).linhas[0];
const casos = Object.entries(AMOSTRAS).flatMap(([chave, amostras]) =>
  amostras.flatMap((a) => [
    [chave, a],
    // vãos largos entre as palavras (sem mexer em pontuação grudada)
    ...(a.includes(" ") && !/^(?:C NPJ|E MAIL|E- MAIL)/.test(a) ? [[chave, a.replace(/ /g, "  ")]] : []),
  ]),
);

describe("rótulos: cada variante impressa é reconhecida por inteiro", () => {
  it.each(casos)("%s ← '%s'", (chave, texto) => {
    const l = linha(texto);
    expect(rotulosDaLinha(l)).toEqual([{ chave, inicio: 0, fim: l.norm.length }]);
  });
});

describe("rótulos: sobreposição e ordem", () => {
  const chaves = (texto: string) => rotulosDaLinha(linha(texto)).map((o) => o.chave);

  it("o rótulo mais longo vence o que está dentro dele", () => {
    expect(chaves("VALOR DO ICMS SUBST.")).toEqual(["V_ST"]);
    expect(chaves("CPF DO BENEFICIARIO")).toEqual(["CNPJ_BENEFICIARIO"]);
    expect(chaves("VALOR TOTAL DOS PRODUTOS")).toEqual(["V_PROD"]);
  });

  it("devolve os rótulos na ordem em que aparecem na linha", () => {
    expect(chaves("VALOR DO FRETE   VALOR DO SEGURO   DESCONTO")).toEqual(["V_FRETE", "V_SEGURO", "DESCONTO"]);
    expect(chaves("DESCONTO   VALOR DO SEGURO   VALOR DO FRETE")).toEqual(["DESCONTO", "V_SEGURO", "V_FRETE"]);
  });

  it("o mesmo rótulo duas vezes aparece duas vezes", () => {
    const o = rotulosDaLinha(linha("TOTAL  X  TOTAL"));
    expect(o).toEqual([
      { chave: "TOTAL", inicio: 0, fim: 5 },
      { chave: "TOTAL", inicio: 10, fim: 15 },
    ]);
  });

  it("palavra colada em outra não é rótulo", () => {
    expect(chaves("TOTALIZADO")).toEqual([]);
    expect(chaves("SUBTOTAL")).toEqual([]);
    expect(chaves("XVALOR")).toEqual([]);
    expect(chaves("sem rótulo nenhum aqui")).toEqual([]);
  });

  it("'valor total da nota fiscal de serviço' não é o total da NF-e", () => {
    expect(chaves("VALOR TOTAL DA NOTA FISCAL DE SERVIÇOS")).toEqual(["VALOR_TOTAL_NOTA"]);
    expect(rotulosDaLinha(linha("VALOR TOTAL DA NOTA FISCAL DE SERVIÇOS"))[0]).toMatchObject({ inicio: 0, fim: 19 });
  });

  it("a mesma linha devolve sempre o mesmo resultado (cache)", () => {
    const l = linha("VALOR TOTAL");
    expect(rotulosDaLinha(l)).toBe(rotulosDaLinha(l));
  });
});
